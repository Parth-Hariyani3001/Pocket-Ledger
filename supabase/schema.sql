create or replace function public.category_owned_by_current_user(target_id bigint)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.categories
    where id = target_id
      and user_id = (select auth.uid())
  );
$$;

