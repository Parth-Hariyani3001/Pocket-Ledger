create table public.categories (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  category_name text not null,
  category_type public.category_type not null,
  color text not null,
  description text,
  parent_category bigint,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint categories_name_not_blank check (length(btrim(category_name)) > 0),
  constraint categories_color_hex check (color ~ '^#[0-9A-Fa-f]{6}$'),
  constraint categories_not_self_parent check (parent_category is distinct from id),
  constraint categories_parent_category_fkey
    foreign key (parent_category) references public.categories (id) on delete cascade
);

create unique index categories_name_unique
  on public.categories (user_id, parent_category, lower(category_name))
  nulls not distinct;

create table public.budget (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  category_id bigint not null references public.categories (id) on delete cascade,
  amount numeric(14, 2) not null,
  start_date date not null,
  end_date date not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint budget_amount_positive check (amount > 0),
  constraint budget_date_range check (start_date <= end_date),
  constraint budget_no_overlap exclude using gist (
    user_id with =,
    category_id with =,
    daterange(start_date, end_date, '[]') with &&
  )
);

create table public.debt (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  counterparty text not null,
  debt_type public.debt_type not null,
  principal numeric(14, 2) not null,
  start_date date not null,
  due_date date,
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint debt_counterparty_not_blank check (length(btrim(counterparty)) > 0),
  constraint debt_principal_positive check (principal > 0),
  constraint debt_due_after_start check (due_date is null or due_date >= start_date)
);

create table public.position (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  name text not null,
  kind public.position_kind not null,
  notes text,
  monthly_amount numeric(14, 2),
  market_value numeric(14, 2),
  valued_on date,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint position_name_not_blank check (length(btrim(name)) > 0),
  constraint position_monthly_amount_positive check (monthly_amount is null or monthly_amount > 0),
  constraint position_market_value_nonnegative check (market_value is null or market_value >= 0),
  constraint position_value_has_date check (
    (market_value is null and valued_on is null)
    or (market_value is not null and valued_on is not null)
  )
);

create table public.transaction (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  amount numeric(14, 2) not null,
  direction public.transaction_direction not null,
  transaction_date date not null,
  description text,
  category_id bigint references public.categories (id) on delete restrict,
  debt_id bigint references public.debt (id) on delete restrict,
  position_id bigint references public.position (id) on delete restrict,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint transaction_amount_positive check (amount > 0),
  constraint transaction_one_subject check (
    num_nonnulls(category_id, debt_id, position_id) = 1
  )
);

