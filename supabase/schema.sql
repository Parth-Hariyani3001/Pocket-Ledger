-- ---------------------------------------------------------------------------
-- Integrity triggers
-- These run as the function owner so they can compare ownership even when RLS
-- hides the other row. search_path is pinned so the body cannot be hijacked.
-- ---------------------------------------------------------------------------

create or replace function public.touch_updated_at()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  new.updated_at := now();
  return new;
end;
$$;

create or replace function public.reject_user_id_change()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  if tg_op = 'UPDATE' and new.user_id is distinct from old.user_id then
    raise exception 'user_id cannot be changed';
  end if;
  return new;
end;
$$;

create or replace function public.categories_validate()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  parent public.categories%rowtype;
begin
  new.category_name := btrim(new.category_name);

  if new.parent_category is not null then
    if exists (
      select 1 from public.categories child where child.parent_category = new.id
    ) then
      raise exception 'A category that already has children cannot become a child';
    end if;

    select * into parent
    from public.categories
    where id = new.parent_category;

    if not found or parent.user_id is distinct from new.user_id then
      raise exception 'Parent category must belong to the same user';
    end if;

    if parent.parent_category is not null then
      raise exception 'Categories are only one level deep';
    end if;

    if parent.category_type is distinct from new.category_type then
      raise exception 'A child category must use the same type as its parent';
    end if;
  end if;

  return new;
end;
$$;

create or replace function public.categories_sync_children()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if new.category_type is distinct from old.category_type then
    update public.categories
    set category_type = new.category_type
    where parent_category = new.id
      and category_type is distinct from new.category_type;
  end if;
  return null;
end;
$$;

create or replace function public.debt_normalize()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  new.counterparty := btrim(new.counterparty);
  if new.notes is not null then
    new.notes := nullif(btrim(new.notes), '');
  end if;
  return new;
end;
$$;

create or replace function public.position_normalize()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  new.name := btrim(new.name);
  if new.notes is not null then
    new.notes := nullif(btrim(new.notes), '');
  end if;
  return new;
end;
$$;

create or replace function public.budget_validate()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  category_user uuid;
  category_parent bigint;
begin
  select user_id, parent_category
  into category_user, category_parent
  from public.categories
  where id = new.category_id;

  if category_user is null or category_user is distinct from new.user_id then
    raise exception 'Budget category must belong to the same user';
  end if;

  if category_parent is not null then
    raise exception 'Budgets can only be set on a parent category';
  end if;

  return new;
end;
$$;

create or replace function public.transaction_validate()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  category_user uuid;
  category_kind public.category_type;
  debt_user uuid;
  position_user uuid;
begin
  if new.description is not null then
    new.description := nullif(btrim(new.description), '');
  end if;

  if new.category_id is not null then
    select user_id, category_type
    into category_user, category_kind
    from public.categories
    where id = new.category_id;

    if category_user is null or category_user is distinct from new.user_id then
      raise exception 'Transaction category must belong to the same user';
    end if;

    if category_kind = 'income' and new.direction <> 'inflow' then
      raise exception 'Income categories only accept inflow transactions';
    end if;

    if category_kind = 'expense' and new.direction <> 'outflow' then
      raise exception 'Expense categories only accept outflow transactions';
    end if;
  end if;

  if new.debt_id is not null then
    select user_id into debt_user
    from public.debt
    where id = new.debt_id;

    if debt_user is null or debt_user is distinct from new.user_id then
      raise exception 'Transaction debt must belong to the same user';
    end if;
  end if;

  if new.position_id is not null then
    select user_id into position_user
    from public.position
    where id = new.position_id;

    if position_user is null or position_user is distinct from new.user_id then
      raise exception 'Transaction position must belong to the same user';
    end if;
  end if;

  return new;
end;
$$;

